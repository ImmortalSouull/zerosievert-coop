"""Generates mod/gml/gml_GlobalScript_coop_lang.gml from mod/lang/strings.tsv (run by tools/build.sh).

strings.tsv: one row per text the mod shows, one column per game language (the folder names under
ZS_vanilla/languages, i.e. the values of global.language_current). The English column is the key: it is what the
code passes to coop_t("English", "Russian") / coop_tf("English {0}", "Russian {0}", args). {0} {1} are filled in
by coop_tf. An empty cell falls back to English (Russian: to the code's own Russian text).
Check for texts the table doesn't have yet: python tools/lang_extract.py
"""
import csv
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "mod", "lang", "strings.tsv")
OUT = os.path.join(ROOT, "mod", "gml", "gml_GlobalScript_coop_lang.gml")


def gml_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    with open(SRC, encoding="utf-8", newline="") as f:
        rows = list(csv.reader(f, delimiter="\t", quoting=csv.QUOTE_NONE))
    head, rows = rows[0], [r for r in rows[1:] if r and r[0] != ""]
    assert head[0] == "english", head
    for r in rows:
        assert len(r) == len(head), r[0]
    nl = "\n"
    out = [
        "// GENERATED by tools/make_lang.py from mod/lang/strings.tsv - edit the table, not this file.",
        "// Texts of the mod in every language of the game. The language follows the game's own setting",
        "// (global.language_current, which the game also takes from Steam / Epic at first start).",
        "",
        "// Translated text for the game's current language. _en is the key in mod/lang/strings.tsv; _ru is the",
        "// fallback when the table has no Russian text (the code keeps both so it reads well without the table).",
        "function coop_t(_en, _ru)",
        "{",
        '    var _l = variable_global_exists("language_current") ? string(global.language_current) : "english";',
        '    if (_l == "english")',
        "    {",
        "        return _en;",
        "    }",
        "    var _d = coop_lang_data();",
        "    if (variable_struct_exists(_d.index, _en) && variable_struct_exists(_d.langs, _l))",
        "    {",
        "        var _a = variable_struct_get(_d.langs, _l);",
        "        var _s = _a[variable_struct_get(_d.index, _en)];",
        '        if (_s != "")',
        "        {",
        "            return _s;",
        "        }",
        "    }",
        '    return (_l == "russian") ? _ru : _en;',
        "}",
        "",
        "// coop_t with {0} / {1} filled in (names, item names, versions): word order differs between languages.",
        'function coop_tf(_en, _ru, _a0 = "", _a1 = "")',
        "{",
        '    return string_replace_all(string_replace_all(coop_t(_en, _ru), "{0}", string(_a0)), "{1}", string(_a1));',
        "}",
        "",
        "// The languages the table covers (english first).",
        "function coop_lang_list()",
        "{",
        "    return [" + ", ".join(gml_str(h) for h in head) + "];",
        "}",
        "",
        "function coop_lang_data()",
        "{",
        "    static _d = undefined;",
        "    if (is_undefined(_d))",
        "    {",
        "        _d = { index: {}, langs: {} };",
    ]
    for i, r in enumerate(rows):
        out.append("        variable_struct_set(_d.index, %s, %d);" % (gml_str(r[0]), i))
    for c in range(1, len(head)):
        out.append("        variable_struct_set(_d.langs, %s, [%s]);" % (gml_str(head[c]), ", ".join(gml_str(r[c]) for r in rows)))
    out += ["    }", "    return _d;", "}", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(nl.join(out))
    print("coop_lang.gml: %d texts x %d languages" % (len(rows), len(head)))


if __name__ == "__main__":
    main()
